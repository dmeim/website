/**
 * Generates src/ui/icons/glyphs-island.ts and glyphs-page.ts: the inner SVG
 * markup of each Phosphor icon listed in src/ui/icons/registry.ts, in the
 * weights the site uses. Run with `npm run icons` after editing the lists.
 */
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";

const root = process.cwd();
const registry = fs.readFileSync(path.join(root, "src/ui/icons/registry.ts"), "utf8");
const phosphor = await import(
  pathToFileURL(path.join(root, "node_modules/@phosphor-icons/react/dist/ssr/index.es.js")).href
);
const weights = ["regular", "bold", "fill", "light"];

function listNames(constName) {
  const match = registry.match(new RegExp(`export const ${constName} = \\[([\\s\\S]*?)\\] as const;`));
  if (!match) throw new Error(`${constName} not found in registry.ts`);
  return [...match[1].matchAll(/"([a-z0-9-]+)"/g)].map(([, name]) => name);
}

function pascal(name) {
  return name.replace(/(^|-)([a-z0-9])/g, (_, __, c) => c.toUpperCase());
}

function glyph(name, weight) {
  const Component = phosphor[pascal(name)];
  if (!Component) throw new Error(`Phosphor has no icon named ${pascal(name)} (${name})`);
  return renderToStaticMarkup(createElement(Component, { weight }))
    .replace(/^<svg[^>]*>/, "")
    .replace(/<\/svg>$/, "")
    .replace('<rect width="256" height="256" fill="none"></rect>', "");
}

function write(file, constName, names) {
  const body = names
    .map((name) => {
      const entries = weights.map((weight) => `    ${weight}: ${JSON.stringify(glyph(name, weight))},`).join("\n");
      return `  "${name}": {\n${entries}\n  },`;
    })
    .join("\n");
  const source = `// Generated by scripts/build-icons.mjs from @phosphor-icons/react. Do not edit.\n\nexport const ${constName} = {\n${body}\n} as const;\n`;
  fs.writeFileSync(path.join(root, "src/ui/icons", file), source);
  console.log(`${file}: ${names.length} icons`);
}

write("glyphs-island.ts", "islandGlyphs", listNames("islandIconNames"));
write("glyphs-page.ts", "pageGlyphs", listNames("pageIconNames"));
